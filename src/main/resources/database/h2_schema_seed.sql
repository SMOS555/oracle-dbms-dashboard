-- =========================================================
-- CLOUD-RESILIENT ORACLE-COMPATIBLE SCHEMA & SEED DATA
-- Used automatically when deploying on free cloud platforms (Render/AWS)
-- without a heavy external Oracle XE instance.
-- =========================================================

CREATE TABLE IF NOT EXISTS CITY (
    CITY VARCHAR(50) PRIMARY KEY,
    STATE VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS SUPPLIER (
    SUPPLIERID VARCHAR(10) PRIMARY KEY,
    SNAME VARCHAR(100),
    CITY VARCHAR(50),
    FOREIGN KEY (CITY) REFERENCES CITY(CITY) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS SUPPLIER_PHONE (
    SUPPLIERID VARCHAR(10) NOT NULL,
    PHONE VARCHAR(20) NOT NULL,
    PRIMARY KEY (SUPPLIERID, PHONE),
    FOREIGN KEY (SUPPLIERID) REFERENCES SUPPLIER(SUPPLIERID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS PRODUCT (
    PRODUCTID VARCHAR(10) PRIMARY KEY,
    PNAME VARCHAR(100) NOT NULL,
    CATEGORY VARCHAR(50) NOT NULL,
    UNITPRICE DECIMAL(10,2) CHECK (UNITPRICE >= 0)
);

CREATE TABLE IF NOT EXISTS PERISHABLE_PRODUCT (
    PRODUCTID VARCHAR(10) PRIMARY KEY,
    SHELFLIFEDAYS INT CHECK (SHELFLIFEDAYS > 0),
    STORAGETEMPC VARCHAR(50),
    FOREIGN KEY (PRODUCTID) REFERENCES PRODUCT(PRODUCTID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS HAZARDOUS_PRODUCT (
    PRODUCTID VARCHAR(10) PRIMARY KEY,
    HAZARDCLASS VARCHAR(100),
    HANDLINGNOTE VARCHAR(200),
    FOREIGN KEY (PRODUCTID) REFERENCES PRODUCT(PRODUCTID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS SUPPLIES (
    SUPPLIERID VARCHAR(10) NOT NULL,
    PRODUCTID VARCHAR(10) NOT NULL,
    LEADTIMEDAYS INT,
    PRIMARY KEY (SUPPLIERID, PRODUCTID),
    FOREIGN KEY (SUPPLIERID) REFERENCES SUPPLIER(SUPPLIERID) ON DELETE CASCADE,
    FOREIGN KEY (PRODUCTID) REFERENCES PRODUCT(PRODUCTID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS INSPECTION (
    INSPID VARCHAR(10) PRIMARY KEY,
    SUPPLIERID VARCHAR(10) NOT NULL,
    PRODUCTID VARCHAR(10) NOT NULL,
    INSPDATE DATE NOT NULL,
    RESULT VARCHAR(50),
    FOREIGN KEY (SUPPLIERID) REFERENCES SUPPLIER(SUPPLIERID) ON DELETE CASCADE,
    FOREIGN KEY (PRODUCTID) REFERENCES PRODUCT(PRODUCTID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS WAREHOUSE (
    WAREHOUSEID VARCHAR(10) PRIMARY KEY,
    WNAME VARCHAR(100) NOT NULL,
    CITY VARCHAR(50),
    CAPACITY INT,
    MANAGERID VARCHAR(10)
);

CREATE TABLE IF NOT EXISTS EMPLOYEE (
    EMPID VARCHAR(10) PRIMARY KEY,
    ENAME VARCHAR(100),
    ROLE VARCHAR(50),
    SALARY DECIMAL(12,2) CHECK (SALARY >= 0),
    WAREHOUSEID VARCHAR(10),
    SUPERVISORID VARCHAR(10)
);

CREATE TABLE IF NOT EXISTS MANAGER (
    EMPID VARCHAR(10) PRIMARY KEY,
    LEVELNO VARCHAR(50),
    BONUS DECIMAL(10,2),
    FOREIGN KEY (EMPID) REFERENCES EMPLOYEE(EMPID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS DRIVER (
    EMPID VARCHAR(10) PRIMARY KEY,
    LICENSENO VARCHAR(50),
    EXPIRY DATE,
    FOREIGN KEY (EMPID) REFERENCES EMPLOYEE(EMPID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS DRIVER_CITY (
    DRIVERID VARCHAR(10) NOT NULL,
    CITY VARCHAR(50) NOT NULL,
    PRIMARY KEY (DRIVERID, CITY),
    FOREIGN KEY (DRIVERID) REFERENCES DRIVER(EMPID) ON DELETE CASCADE,
    FOREIGN KEY (CITY) REFERENCES CITY(CITY) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS STOCK (
    WAREHOUSEID VARCHAR(10) NOT NULL,
    PRODUCTID VARCHAR(10) NOT NULL,
    QUANTITY INT CHECK (QUANTITY >= 0),
    PRIMARY KEY (WAREHOUSEID, PRODUCTID),
    FOREIGN KEY (WAREHOUSEID) REFERENCES WAREHOUSE(WAREHOUSEID) ON DELETE CASCADE,
    FOREIGN KEY (PRODUCTID) REFERENCES PRODUCT(PRODUCTID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS CUSTOMER (
    CUSTID VARCHAR(10) PRIMARY KEY,
    CNAME VARCHAR(100) NOT NULL,
    STREET VARCHAR(100),
    CITY VARCHAR(50),
    PHONE VARCHAR(20),
    FOREIGN KEY (CITY) REFERENCES CITY(CITY) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS ORDERS (
    ORDERID VARCHAR(10) PRIMARY KEY,
    ORDERDATE DATE NOT NULL,
    STATUS VARCHAR(30),
    CUSTID VARCHAR(10) NOT NULL,
    FOREIGN KEY (CUSTID) REFERENCES CUSTOMER(CUSTID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS ORDER_ITEM (
    ORDERID VARCHAR(10) NOT NULL,
    PRODUCTID VARCHAR(10) NOT NULL,
    QTY INT CHECK (QTY > 0),
    PRICE DECIMAL(10,2) CHECK (PRICE >= 0),
    PRIMARY KEY (ORDERID, PRODUCTID),
    FOREIGN KEY (ORDERID) REFERENCES ORDERS(ORDERID) ON DELETE CASCADE,
    FOREIGN KEY (PRODUCTID) REFERENCES PRODUCT(PRODUCTID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS ORDER_DRIVER (
    ORDERID VARCHAR(10) NOT NULL,
    DRIVERID VARCHAR(10) NOT NULL,
    PRIMARY KEY (ORDERID, DRIVERID),
    FOREIGN KEY (ORDERID) REFERENCES ORDERS(ORDERID) ON DELETE CASCADE,
    FOREIGN KEY (DRIVERID) REFERENCES DRIVER(EMPID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS DELIVERY_DUTY (
    ORDERID VARCHAR(10) NOT NULL,
    DRIVERID VARCHAR(10) NOT NULL,
    CITY VARCHAR(50) NOT NULL,
    PRIMARY KEY (ORDERID, CITY),
    FOREIGN KEY (ORDERID) REFERENCES ORDERS(ORDERID) ON DELETE CASCADE,
    FOREIGN KEY (DRIVERID) REFERENCES DRIVER(EMPID) ON DELETE CASCADE,
    FOREIGN KEY (CITY) REFERENCES CITY(CITY) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS GOODS_MOVEMENT (
    MOVEMENTID VARCHAR(10) PRIMARY KEY,
    ORDERID VARCHAR(10) NOT NULL,
    WAREHOUSEID VARCHAR(10) NOT NULL,
    MOVEDATE DATE,
    STATUS VARCHAR(30),
    FOREIGN KEY (ORDERID) REFERENCES ORDERS(ORDERID) ON DELETE CASCADE,
    FOREIGN KEY (WAREHOUSEID) REFERENCES WAREHOUSE(WAREHOUSEID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS SHIPMENT (
    MOVEMENTID VARCHAR(10) PRIMARY KEY,
    DELIVERYDATE DATE,
    FOREIGN KEY (MOVEMENTID) REFERENCES GOODS_MOVEMENT(MOVEMENTID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS GOODS_RETURN (
    MOVEMENTID VARCHAR(10) PRIMARY KEY,
    REASON VARCHAR(200),
    REFUNDAMT DECIMAL(10,2),
    FOREIGN KEY (MOVEMENTID) REFERENCES GOODS_MOVEMENT(MOVEMENTID) ON DELETE CASCADE
);

